// Jednoduchý súbor .xlsx bez knižníc (rozhodnutie 2026-10-12: export zoznamov).
// Jeden hárok; text sa zapisuje ako text (IČO/OIB, telefóny, EIC nestratia úvodné nuly), čísla ako čísla.
// XLSX = ZIP s niekoľkými XML súbormi; ZIP bez kompresie (metóda „stored“) stačí a nepotrebuje knižnicu.

export type Cell = string | number | null | undefined;

const enc = new TextEncoder();

const xml = (s: string) =>
  s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    // znaky, ktoré XML nepovoľuje
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, '');

function colName(i: number): string {
  let s = '';
  for (let n = i + 1; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + ((n - 1) % 26)) + s;
  return s;
}

function sheetXml(header: string[], rows: Cell[][], widths: number[]): string {
  const cols = widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('');
  const row = (cells: Cell[], r: number, style: number) =>
    `<row r="${r}">` +
    cells
      .map((v, c) => {
        const ref = `${colName(c)}${r}`;
        if (v === null || v === undefined || v === '') return '';
        if (typeof v === 'number' && Number.isFinite(v)) return `<c r="${ref}" s="${style}"><v>${v}</v></c>`;
        return `<c r="${ref}" t="inlineStr" s="${style}"><is><t xml:space="preserve">${xml(String(v))}</t></is></c>`;
      })
      .join('') +
    '</row>';
  return (
    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>' +
    '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">' +
    '<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>' +
    `<cols>${cols}</cols><sheetData>` +
    row(header, 1, 1) +
    rows.map((r, i) => row(r, i + 2, 0)).join('') +
    `</sheetData><autoFilter ref="A1:${colName(header.length - 1)}${rows.length + 1}"/></worksheet>`
  );
}

